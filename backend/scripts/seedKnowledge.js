function seed() {
  console.log(`开始导入知识库，共 ${CHUNKS.length} 条...`);

  // 清空旧数据
  db.prepare('DELETE FROM knowledge_chunks').run();
  console.log('已清空旧数据');

  // 批量插入
  const stmt = db.prepare(`INSERT INTO knowledge_chunks (subject, chapter, title, content, keywords, difficulty, source) VALUES (?, ?, ?, ?, ?, ?, ?)`);
  const tx = db.transaction((items) => {
    for (const c of items) {
      stmt.run(c.subject, c.chapter, c.title, c.content, c.keywords || '', c.difficulty || 'normal', c.source || '');
    }
  });
  tx(CHUNKS);

  // 统计
  const stats = db.prepare('SELECT subject, COUNT(*) as c FROM knowledge_chunks GROUP BY subject').all();
  console.log('\n导入完成！各科分布：');
  for (const s of stats) {
    console.log(`  ${SUBJECTS[s.subject] || s.subject}: ${s.c} 条`);
  }
  console.log(`\n总计: ${CHUNKS.length} 条`);
}

seed();
